'use strict';

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
global.window = {};
eval(fs.readFileSync(path.join(root, 'data.js'), 'utf8'));

const words = [...new Set(window.IPA_DATA.flatMap((item) => item.examples.map((example) => example.word))) ].sort();
const map = {};

function icibaUrl(word, accent) {
  const hash = crypto.createHash('md5').update(word).digest('hex');
  const disc = accent === 'us' ? '1' : '0';
  return `https://res.iciba.com/resource/amp3/${disc}/0/${hash.slice(0, 2)}/${hash.slice(2, 4)}/${hash}.mp3`;
}

for (const word of words) {
  map[word] = { uk: icibaUrl(word, 'uk'), us: icibaUrl(word, 'us') };
}

const output = '/* Generated by tools/generate-word-audio-map.js. Do not edit manually. */\n' +
  'window.ICIBA_WORD_AUDIO = Object.freeze(' + JSON.stringify(map, null, 2) + ');\n';
fs.writeFileSync(path.join(root, 'word-audio.js'), output, 'utf8');
console.log(`Generated ${words.length} Iciba word audio mappings.`);
